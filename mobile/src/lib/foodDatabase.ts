export function searchFoods(
  foods: FoodItem[],
  query: string,
  categoryFilter: string,
  lang: 'es' | 'en' = 'es'
): FoodItem[] {
  let filtered = foods;

  // Filtrado por categoría
  if (categoryFilter && categoryFilter !== 'all' && categoryFilter !== 'recent') {
    if (categoryFilter === 'custom') {
      filtered = filtered.filter((f) => f.isCustom === true);
    } else {
      filtered = filtered.filter((f) => f.category === categoryFilter);
    }
  }

  // Filtrado por texto
  if (!query || !query.trim()) {
    return filtered;
  }

  const cleanQuery = normalizeText(query.trim());
  const words = cleanQuery.split(/\s+/).filter(Boolean);

  return filtered.filter((item) => {
    const nameEs = normalizeText(item.name_es || item.name || '');
    const nameEn = normalizeText(item.name_en || item.name || '');
    const defaultName = normalizeText(item.name || '');
    const haystack = `${nameEs} ${nameEn} ${defaultName} ${item.category} ${item.servingLabel || ''} ${item.servingLabel_es || ''} ${item.servingLabel_en || ''} ${item.servingUnit === 'rebanada' ? 'rebanada rebanadas feta fetas loncha lonchas tajada tajadas' : ''}`;

    // Cada palabra debe coincidir (soporta plurales comunes como 'claras' -> 'clara', 'huevos' -> 'huevo')
    return words.every((word) => {
      if (haystack.includes(word)) return true;
      if (word.endsWith('es') && word.length > 4 && haystack.includes(word.slice(0, -2))) return true;
      if (word.endsWith('s') && word.length > 3 && haystack.includes(word.slice(0, -1))) return true;
      return false;
    });
  });
}

/**
 * Retorna los alimentos personalizados guardados en AsyncStorage
 */
export async function getCustomFoods(): Promise<FoodItem[]> {
  try {
    const raw = await AsyncStorage.getItem(STORAGE_KEY_CUSTOM_FOODS);
    if (!raw) return [];
    return JSON.parse(raw);
  } catch (e) {
    console.warn('Error fetching custom foods:', e);
    return [];
  }
}

/**
 * Guarda un nuevo alimento personalizado
 */
export async function saveCustomFood(food: Omit<FoodItem, 'id' | 'isCustom'>): Promise<FoodItem> {
  const newItem: FoodItem = {
    ...food,
    id: `custom_${Date.now()}_${Math.random().toString(36).substr(2, 5)}`,
    name_es: food.name_es || food.name,
    name_en: food.name_en || food.name,
    isCustom: true,
  };

  try {
    const existing = await getCustomFoods();
    const updated = [newItem, ...existing];
    await AsyncStorage.setItem(STORAGE_KEY_CUSTOM_FOODS, JSON.stringify(updated));
    return newItem;
  } catch (e) {
    console.warn('Error saving custom food:', e);
    return newItem;
  }
}

/**
 * Elimina un alimento personalizado
 */
export async function deleteCustomFood(id: string): Promise<void> {
  try {
    const existing = await getCustomFoods();
    const updated = existing.filter((f) => f.id !== id);
    await AsyncStorage.setItem(STORAGE_KEY_CUSTOM_FOODS, JSON.stringify(updated));
  } catch (e) {
    console.warn('Error deleting custom food:', e);
  }
}

/**
 * Retorna todos los alimentos (predefinidos + personalizados del usuario)
 */
export async function getAllFoods(): Promise<FoodItem[]> {
  const custom = await getCustomFoods();
  return [...custom, ...PRELOADED_FOODS];
}

/**
 * Calcula los macros para una porción dada (en unidades o en gramos)
 */
export function calculateFoodMacros(
  food: FoodItem,
  quantity: number,
  targetUnit: ServingUnit
): {
  calories: number;
  protein_g: number;
  carbs_g: number;
  fats_g: number;
} {
  if (quantity <= 0) {
    return { calories: 0, protein_g: 0, carbs_g: 0, fats_g: 0 };
  }

  const sliceWeight = food.unitWeightGrams || 25;
  const unitWeight = food.unitWeightGrams || (food.servingUnit === 'unidad' ? (food.defaultServingSize > 1 ? food.defaultServingSize : 100) : (food.servingUnit === 'rebanada' ? 25 : 100));

  let factor = 1;

  if (food.servingUnit === targetUnit) {
    factor = quantity / (food.defaultServingSize || 1);
  } else if (targetUnit === 'rebanada') {
    if (food.servingUnit === 'gramos') {
      const totalGrams = quantity * sliceWeight;
      factor = totalGrams / (food.defaultServingSize || 100);
    } else {
      factor = quantity / (food.defaultServingSize || 1);
    }
  } else if (food.servingUnit === 'rebanada') {
    if (targetUnit === 'gramos') {
      const slices = quantity / sliceWeight;
      factor = slices / (food.defaultServingSize || 1);
    } else {
      factor = quantity / (food.defaultServingSize || 1);
    }
  } else if (food.servingUnit === 'gramos' && targetUnit === 'unidad') {
    const grams = quantity * unitWeight;
    factor = grams / (food.defaultServingSize || 100);
  } else if (food.servingUnit === 'unidad' && targetUnit === 'gramos') {
    const units = quantity / unitWeight;
    factor = units / (food.defaultServingSize || 1);
  }

  return {
    calories: Math.round(food.calories * factor),
    protein_g: Number((food.protein_g * factor).toFixed(1)),
    carbs_g: Number((food.carbs_g * factor).toFixed(1)),
    fats_g: Number((food.fats_g * factor).toFixed(1)),
  };
}

