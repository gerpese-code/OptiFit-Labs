/**
 * Normaliza un texto para búsquedas (minúsculas y sin acentos ni diacríticos)
 */
export function normalizeText(str: string): string {
  if (!str) return '';
  return str
    .toLowerCase()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '');
}

